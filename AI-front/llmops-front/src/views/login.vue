<script>
import api_auth from "@/api/auth";
import RSAUtils from "@/utils/rsaUtil";
import loginResetModal from "./login-reset-modal";
import { clearLoginInfo } from "@/utils/base";
import nativeAxios from "axios";
import logo from "@/assets/login/logo.png";
import n from "@/assets/login/n.png";
import p from "@/assets/login/p.png";
import c from "@/assets/login/c.png";
export default {
  components: {
    loginResetModal
  },
  created() {
    this.getNeedCode();
  },
  mounted() {
    this.onResize();
    this.getVersion();
    window.addEventListener("resize", this.onResize);
  },
  destroyed() {
    window.removeEventListener("resize", this.onResize);
  },
  computed: {},
  data() {
    return {
      logo,
      n,
      p,
      c,
      globalConfig: window.globalConfig,
      loading: false,
      needLoginCode: false,
      codeImg: null,
      formData: {
        username: "",
        password: "",
        code: null
      },
      version: null,
      inputType: "password"
    };
  },
  methods: {
    // 获取版本号
    getVersion() {
      nativeAxios
        .get("./version.json")
        .then(res => {
          if (res.data) {
            let str = res.data.version;
            let version = str
              .split(".")
              .filter((it, idx) => idx < 3)
              .join(".");
            this.version =
              version.charAt(0).toUpperCase() === "V"
                ? version
                : `V ${version}`;
            localStorage.setItem("currentVersion", JSON.stringify(res.data));
          }
        })
        .catch(err => {
          localStorage.removeItem("currentVersion");
        });
    },
    onResize() {
      const w = document.body.clientWidth;
      const h = document.body.clientHeight;
      const nw = 1920;
      const nh = 1080;
      var left, top, scale;
      if (w / h > nw / nh) {
        scale = h / nh;
        top = 0;
        left = (w - nw * scale) / 2;
      } else {
        scale = w / nw;
        left = 0;
        top = (h - nh * scale) / 2;
      }
      document
        .getElementById("main")
        .setAttribute(
          "style",
          "transform: scale(" +
            scale +
            ");left:" +
            left +
            "px;top:" +
            top +
            "px;"
        );
    },
    getNeedCode() {
      api_auth.getNeedCode().then(resData => {
        this.needLoginCode = resData;
        if (this.needLoginCode) {
          this.getImgCode();
        }
      });
    },
    getImgCode() {
      // api_auth.getImgCode().then(data => this.codeImg = data);
      this.codeImg =
        window.globalConfig.defaultProxyPath +
        "/sso/code/80/37/10/25/20?t=" +
        new Date().getTime();
    },
    showMessage(msg) {
      this.$message({
        message: msg,
        type: "error",
        duration: 1500
      });
    },
    // 提交表单
    formDataSubmit() {
      if (!this.formData.username) {
        this.showMessage("请输入用户名");
        return;
      }
      if (!this.formData.password) {
        this.showMessage("请输入密码");
        return;
      }
      // 后台可以对验证码进行开关，所以不一定必填验证码
      /* if (!this.formData.code) {
        this.showMessage("请输入验证码");
        return;
      } */

      this.loading = true;

      api_auth
        .getKeyPair()
        .then(resData => {
          const publicKey = RSAUtils.getKeyPair(
            resData.exponent,
            "",
            resData.modulus
          );
          const o = {
            userName: this.formData.username,
            password: RSAUtils.encryptedString(
              publicKey,
              this.formData.password
            ),
            code: this.formData.code,
            appKey: window.globalConfig.appKey
          };

          api_auth
            .login(o)
            .then(async data => {
              // 登录成功后，清空原来的身份信息
              clearLoginInfo();

              // 初始化项目信息
              await this.$store.dispatch('project/initProject', this.formData.username);

              this.loading = false;

              const target = this.$route.params.target;
              console.debug(`start jump to ${target || "/"}`);
              if (target) {
                this.$router.replace(target).catch(e => {
                  console.error("loginError router.replace target", e);
                });
              } else {
                window.globalCache.autoShowCompass = true;
                this.$router.replace({ path: "/" }).catch(e => {
                  console.error("loginError router.replace /", e);
                });
              }
              console.debug("login end");
              window.globalCache.checkPasswordExpire = true;
            })
            .catch(e => {
              console.error("loginError login", e);
              this.loading = false;
              this.getImgCode();
            });
        })
        .catch(e => {
          this.loading = false;
          console.error("loginError getKeyPair", e);
        });
    },
    togglePasswordVisibility() {
      if (this.inputType === "password") this.inputType = "text";
      else this.inputType = "password";
    },
    // 重置密码
    cliRetrieve() {
      this.$refs.loginResetModal.init();
    }
  }
};
</script>

